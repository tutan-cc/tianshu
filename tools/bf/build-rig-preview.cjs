// Package the preview as one HTML file: works in isolated previews and offline.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
const portraits = {};
for (const mood of ['calm', 'urgent', 'happy']) {
  portraits[mood] = 'data:image/png;base64,' + fs.readFileSync(
    path.join(root, 'art/icons/faces/stud_' + mood + '.png')).toString('base64');
}
const rig = fs.readFileSync(path.join(root, 'breakfast-rig.js'), 'utf8');
const template = fs.readFileSync(path.join(__dirname, 'rig-preview.template.html'), 'utf8');
const html = template.replace('<script src="breakfast-rig.js"></script>',
  '<!-- Generated by tools/bf/build-rig-preview.cjs; edit the template or rig source. -->\n' +
  '<script>\n' + rig.replace(/<\/script/gi, '<\\/script') + '\n</script>')
  .replace("  var images={},mood='calm'", '  var portraitSources=' + JSON.stringify(portraits) + ";\n  var images={},mood='calm'")
  .replace("img.src='art/icons/faces/stud_'+k+'.png'", 'img.src=portraitSources[k]');
if (/<script\s+src=/.test(html) || /img\.src='art\//.test(html)) {
  throw new Error('Preview still depends on external resources');
}
fs.writeFileSync(path.join(root, 'breakfast-rig-preview.html'), html, 'utf8');
console.log('Standalone preview built:', Buffer.byteLength(html), 'bytes');
